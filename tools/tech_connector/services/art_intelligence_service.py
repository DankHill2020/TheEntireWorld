def _unique_text(items: Iterable[str]) -> list[str]:
    unique: list[str] = []
    seen: set[str] = set()
    for item in items:
        key = item.casefold()
        if key in seen:
            continue
        seen.add(key)
        unique.append(item)
    return unique


def _extract_palette(image: Any, count: int = 5) -> list[str]:
    quantized = image.convert("RGB").quantize(colors=count, method=2)
    palette = quantized.getpalette() or []
    colors = quantized.getcolors(maxcolors=256) or []
    colors.sort(reverse=True)
    swatches: list[str] = []
    for _pixels, index in colors[:count]:
        offset = int(index) * 3
        if offset + 2 < len(palette):
            swatches.append("#%02X%02X%02X" % tuple(palette[offset : offset + 3]))
    return swatches


def _brightest_region(image: Any) -> str:
    gray = image.convert("L")
    width, height = gray.size
    regions = {
        "upper-left": (0, 0, width // 2, height // 2),
        "upper-right": (width // 2, 0, width, height // 2),
        "lower-left": (0, height // 2, width // 2, height),
        "lower-right": (width // 2, height // 2, width, height),
        "center": (width // 4, height // 4, width * 3 // 4, height * 3 // 4),
    }
    try:
        from PIL import ImageStat

        scores = {
            name: float(ImageStat.Stat(gray.crop(box)).mean[0])
            for name, box in regions.items()
            if box[2] > box[0] and box[3] > box[1]
        }
    except Exception:
        return "unknown"
    return max(scores, key=scores.get) if scores else "unknown"


def _threshold_ratio(image: Any, below: int | None = None, above: int | None = None) -> float:
    gray = image.convert("L")
    pixel_reader = getattr(gray, "get_flattened_data", None) or gray.getdata
    pixels = list(pixel_reader())
    if not pixels:
        return 0.0
    if below is not None:
        return sum(1 for value in pixels if value < below) / len(pixels)
    if above is not None:
        return sum(1 for value in pixels if value > above) / len(pixels)
    return 0.0


def _edge_density(image: Any) -> float:
    gray = image.convert("L")
    width, height = gray.size
    if width < 2 or height < 2:
        return 0.0
    pixels = gray.load()
    total = 0
    edges = 0
    for y in range(height - 1):
        for x in range(width - 1):
            dx = abs(int(pixels[x, y]) - int(pixels[x + 1, y]))
            dy = abs(int(pixels[x, y]) - int(pixels[x, y + 1]))
            if math.hypot(dx, dy) > 32:
                edges += 1
            total += 1
    return edges / max(1, total)


