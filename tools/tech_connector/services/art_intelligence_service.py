def compare_visual_renders(ref_image_id: str, current_render_id: str) -> dict[str, Any]:
    """Compare two images using simple palette/value evidence when decodable."""
    ref = analyze_image_art_context(ref_image_id)
    cur = analyze_image_art_context(current_render_id)
    if ref.media_type != "image" or cur.media_type != "image":
        return {
            "reference_id": ref_image_id,
            "current_render_id": current_render_id,
            "ok": False,
            "reason": "Both inputs must be decodable images for local comparison.",
        }
    ref_e = ref.evidence
    cur_e = cur.evidence
    luma_delta = abs(float(ref_e.get("mean_luma", 0)) - float(cur_e.get("mean_luma", 0)))
    contrast_delta = abs(float(ref_e.get("contrast_stddev", 0)) - float(cur_e.get("contrast_stddev", 0)))
    palette_overlap = len(set(ref.color_palette[:5]) & set(cur.color_palette[:5])) / max(1, len(set(ref.color_palette[:5])))
    return {
        "reference_id": ref_image_id,
        "current_render_id": current_render_id,
        "ok": True,
        "value_structure_match": _score_from_delta(luma_delta, 128),
        "contrast_match": _score_from_delta(contrast_delta, 80),
        "palette_match": round(palette_overlap, 3),
        "differences": [
            {
                "category": "value",
                "description": f"Mean luma differs by {luma_delta:.1f}/255.",
                "suggested_dcc_action": "Adjust exposure or key/fill balance if this diverges from the reference.",
            },
            {
                "category": "contrast",
                "description": f"Contrast stddev differs by {contrast_delta:.1f}.",
                "suggested_dcc_action": "Tune fill, ambient light, or post-process contrast.",
            },
        ],
    }


def inspect_visual_region(
    image_id: str,
    bbox: tuple[float, float, float, float],
    label: str = "selected_region",
) -> dict[str, Any]:
    """Analyze a selected image region using measured color/value stats."""
    try:
        from PIL import Image, ImageStat

        with Image.open(image_id) as opened:
            image = opened.convert("RGB")
        width, height = image.size
        x1, y1, x2, y2 = bbox
        crop_box = (
            max(0, min(width, int(x1 * width))),
            max(0, min(height, int(y1 * height))),
            max(0, min(width, int(x2 * width))),
            max(0, min(height, int(y2 * height))),
        )
        crop = image.crop(crop_box)
        stat = ImageStat.Stat(crop.convert("L"))
        palette = _extract_palette(crop)
        mean_luma = float(stat.mean[0]) if stat.mean else 0.0
        contrast = float(stat.stddev[0]) if stat.stddev else 0.0
        analysis = {
            "dominant_colors": palette,
            "mean_luma": round(mean_luma, 2),
            "contrast_stddev": round(contrast, 2),
            "recommended_fix": _region_recommendation(mean_luma, contrast),
        }
    except Exception as exc:
        analysis = {"error": str(exc), "recommended_fix": "Could not decode selected region."}

    return {
        "image_id": image_id,
        "region_id": f"region_{int(bbox[0] * 100)}_{int(bbox[1] * 100)}",
        "bbox": list(bbox),
        "label": label,
        "region_analysis": analysis,
    }


