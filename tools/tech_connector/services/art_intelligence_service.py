def _extract_video_sample_frames(path: Path, sample_count: int = 3) -> tuple[list[Path], str]:
    if not path.exists() or not path.is_file():
        return [], "Video file is missing or not readable."

    cv2_frames, cv2_note = _extract_video_frames_with_cv2(path, sample_count)
    if cv2_frames:
        return cv2_frames, cv2_note

    imageio_frames, imageio_note = _extract_video_frames_with_imageio(path, sample_count)
    if imageio_frames:
        return imageio_frames, imageio_note

    ffmpeg_frames, ffmpeg_note = _extract_video_frames_with_ffmpeg(path, sample_count)
    if ffmpeg_frames:
        return ffmpeg_frames, ffmpeg_note

    notes = [cv2_note, imageio_note, ffmpeg_note]
    return [], "No video frame decoder succeeded. " + " ".join(note for note in notes if note)


def _extract_video_frames_with_cv2(path: Path, sample_count: int) -> tuple[list[Path], str]:
    try:
        import cv2  # type: ignore
    except Exception:
        return [], "OpenCV is not installed."

    capture = cv2.VideoCapture(str(path))
    try:
        if not capture.isOpened():
            return [], "OpenCV could not open the video."
        frame_total = int(capture.get(cv2.CAP_PROP_FRAME_COUNT) or 0)
        if frame_total <= 0:
            positions = [0]
        else:
            positions = _sample_positions(frame_total, sample_count)
        output_dir = Path(tempfile.mkdtemp(prefix="tech_connector_video_frames_"))
        frames: list[Path] = []
        for index, frame_number in enumerate(positions):
            capture.set(cv2.CAP_PROP_POS_FRAMES, frame_number)
            ok, frame = capture.read()
            if not ok:
                continue
            output_path = output_dir / f"frame_{index:02d}.png"
            cv2.imwrite(str(output_path), frame)
            frames.append(output_path)
        return frames, f"Sampled {len(frames)} frame(s) with OpenCV."
    finally:
        capture.release()


def _extract_video_frames_with_imageio(path: Path, sample_count: int) -> tuple[list[Path], str]:
    try:
        import imageio.v3 as iio  # type: ignore
        from PIL import Image
    except Exception:
        install_note = _ensure_media_python_dependencies()
        try:
            import imageio.v3 as iio  # type: ignore
            from PIL import Image
        except Exception as exc:
            return [], f"imageio is not installed or could not import after auto-install. {install_note} Import error: {exc}"

    output_dir = Path(tempfile.mkdtemp(prefix="tech_connector_video_frames_"))
    frames: list[Path] = []
    try:
        decoded_frames = []
        for frame in iio.imiter(path):
            decoded_frames.append(frame)
            if len(decoded_frames) >= 90:
                break
        if not decoded_frames:
            return [], "imageio decoded zero frames."
        positions = _sample_positions(len(decoded_frames), sample_count)
        for index, frame_number in enumerate(positions):
            frame = decoded_frames[frame_number]
            output_path = output_dir / f"frame_{index:02d}.png"
            Image.fromarray(frame).save(output_path)
            frames.append(output_path)
    except Exception as exc:
        return [], f"imageio could not sample frames: {exc}"
    return frames, f"Sampled {len(frames)} frame(s) with imageio."


def _extract_video_frames_with_ffmpeg(path: Path, sample_count: int) -> tuple[list[Path], str]:
    ffmpeg = shutil.which("ffmpeg")
    if not ffmpeg:
        try:
            import imageio_ffmpeg  # type: ignore

            ffmpeg = imageio_ffmpeg.get_ffmpeg_exe()
        except Exception:
            ffmpeg = ""
    if not ffmpeg:
        return [], "ffmpeg is not installed or not on PATH."

    output_dir = Path(tempfile.mkdtemp(prefix="tech_connector_video_frames_"))
    output_pattern = output_dir / "frame_%02d.png"
    command = [
        ffmpeg,
        "-hide_banner",
        "-loglevel",
        "error",
        "-i",
        str(path),
        "-vf",
        f"thumbnail,scale=320:-1",
        "-frames:v",
        str(sample_count),
        str(output_pattern),
    ]
    try:
        subprocess.run(command, check=True, capture_output=True, text=True, timeout=30)
    except Exception as exc:
        return [], f"ffmpeg could not sample frames: {exc}"
    frames = sorted(output_dir.glob("frame_*.png"))
    return frames, f"Sampled {len(frames)} frame(s) with ffmpeg."


