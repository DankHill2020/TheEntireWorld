def _camera_settings_profile(prompt_text: str, media_type: str, evidence: dict[str, Any]) -> dict[str, Any]:
    matches = _camera_prompt_matches(prompt_text)
    if not matches:
        return {
            "requested": False,
            "note": "No explicit camera-settings request detected.",
            "matched_features": [],
            "settings_guidance": [],
            "dcc_controls": {},
            "validation_checks": [],
        }

    settings_guidance: list[dict[str, Any]] = []
    dcc_controls: dict[str, list[str]] = {}
    validation_checks: list[str] = []
    for key, data in matches.items():
        settings_guidance.append(
            {
                "feature": key,
                "why": data.get("why", ""),
                "checks": list(data.get("user_checks", ())),
            }
        )
        for dcc, controls in (data.get("dcc_controls") or {}).items():
            dcc_controls.setdefault(dcc, [])
            for control in controls:
                if control not in dcc_controls[dcc]:
                    dcc_controls[dcc].append(control)
        validation_checks.extend(check for check in data.get("user_checks", ()) if check not in validation_checks)

    if media_type == "video":
        validation_checks.extend(
            check
            for check in (
                "Scrub sampled frames for camera drift, handheld jitter, rolling shutter, and motion blur before tracking or mocap.",
                "Confirm frame rate and shutter/motion-blur assumptions before exporting to Unreal, Maya, Blender, or an editor.",
            )
            if check not in validation_checks
        )
    else:
        validation_checks.append("Use a camera overlay or safe frame to verify crop, subject placement, and final delivery aspect.")

    resolution = evidence.get("width") and evidence.get("height")
    measured_note = (
        f"Measured source resolution is {evidence.get('width')}x{evidence.get('height')}."
        if resolution
        else "Source resolution is not available from this media path."
    )

    return {
        "requested": True,
        "note": (
            "Camera settings cannot be solved exactly from pixels alone; this profile maps the prompt "
            "to practical controls and validation checks."
        ),
        "matched_features": list(matches.keys()),
        "settings_guidance": settings_guidance,
        "dcc_controls": dcc_controls,
        "validation_checks": validation_checks,
        "measured_context": measured_note,
    }


