def _format_bytes(size_bytes: int) -> str:
    if size_bytes <= 0:
        return "unknown size"
    units = ["B", "KB", "MB", "GB"]
    value = float(size_bytes)
    for unit in units:
        if value < 1024 or unit == units[-1]:
            return f"{value:.1f} {unit}"
        value /= 1024
    return f"{size_bytes} B"


def _best_match(render_ids: list[str], comparisons: Iterable[dict[str, Any]]) -> str:
    best_id = ""
    best_score = -1.0
    for render_id, comparison in zip(render_ids, comparisons):
        if not comparison.get("ok"):
            continue
        score = (
            float(comparison.get("value_structure_match", 0))
            + float(comparison.get("contrast_match", 0))
            + float(comparison.get("palette_match", 0))
        ) / 3
        if score > best_score:
            best_id = render_id
            best_score = score
    return best_id


