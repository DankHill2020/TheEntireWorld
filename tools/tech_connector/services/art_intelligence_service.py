def _normal_map_from_height(height_image: Any, strength: float = 2.5) -> Any:
    try:
        import numpy as np
        from PIL import Image

        height = np.asarray(height_image.convert("L"), dtype=np.float32) / 255.0
        gy, gx = np.gradient(height)
        nx = -gx * strength
        ny = -gy * strength
        nz = np.ones_like(height)
        length = np.sqrt(nx * nx + ny * ny + nz * nz)
        normal = np.dstack(
            (
                (nx / length * 0.5 + 0.5) * 255.0,
                (ny / length * 0.5 + 0.5) * 255.0,
                (nz / length * 0.5 + 0.5) * 255.0,
            )
        ).clip(0, 255).astype(np.uint8)
        return Image.fromarray(normal)
    except Exception:
        return _normal_map_from_height_without_numpy(height_image, strength)


def _normal_map_from_height_without_numpy(height_image: Any, strength: float = 2.5) -> Any:
    from PIL import Image

    height = height_image.convert("L")
    width, height_px = height.size
    pixels = height.load()
    output = Image.new("RGB", (width, height_px), (128, 128, 255))
    out = output.load()
    for y in range(height_px):
        for x in range(width):
            left = pixels[max(0, x - 1), y] / 255.0
            right = pixels[min(width - 1, x + 1), y] / 255.0
            up = pixels[x, max(0, y - 1)] / 255.0
            down = pixels[x, min(height_px - 1, y + 1)] / 255.0
            nx = -(right - left) * strength
            ny = -(down - up) * strength
            nz = 1.0
            length = math.sqrt(nx * nx + ny * ny + nz * nz) or 1.0
            out[x, y] = (
                int((nx / length * 0.5 + 0.5) * 255),
                int((ny / length * 0.5 + 0.5) * 255),
                int((nz / length * 0.5 + 0.5) * 255),
            )
    return output


def _palette_swatch_image(colors: list[str]) -> Any:
    from PIL import Image, ImageColor

    swatches = colors or ["#000000"]
    width = max(1, len(swatches)) * 64
    image = Image.new("RGB", (width, 64), "#000000")
    for index, color in enumerate(swatches):
        try:
            rgb = ImageColor.getrgb(color)
        except Exception:
            rgb = (0, 0, 0)
        for x in range(index * 64, (index + 1) * 64):
            for y in range(64):
                image.putpixel((x, y), rgb)
    return image


