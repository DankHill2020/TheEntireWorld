@dataclass
class VisualIngestionResult:
    """Structured visual context extracted from an attached image or video."""

    image_id: str
    summary: str
    scene_graph: dict[str, Any] = field(default_factory=dict)
    composition: dict[str, Any] = field(default_factory=dict)
    lighting: dict[str, Any] = field(default_factory=dict)
    shadows: dict[str, Any] = field(default_factory=dict)
    materials: list[dict[str, Any]] = field(default_factory=list)
    color_palette: list[str] = field(default_factory=list)
    camera_spec: dict[str, Any] = field(default_factory=dict)
    cinematography: dict[str, Any] = field(default_factory=dict)
    rendering_spec: dict[str, Any] = field(default_factory=dict)
    production_context: dict[str, Any] = field(default_factory=dict)
    regions: list[dict[str, Any]] = field(default_factory=list)
    art_ontology_matches: dict[str, Any] = field(default_factory=dict)
    possible_tasks: list[str] = field(default_factory=list)
    uncertainties: list[str] = field(default_factory=list)
    confidence: float = 0.45
    media_type: str = "image"
    evidence: dict[str, Any] = field(default_factory=dict)

    def to_dict(self) -> dict[str, Any]:
        return {
            "image_id": self.image_id,
            "summary": self.summary,
            "scene_graph": self.scene_graph,
            "composition": self.composition,
            "lighting": self.lighting,
            "shadows": self.shadows,
            "materials": self.materials,
            "color_palette": self.color_palette,
            "camera_spec": self.camera_spec,
            "cinematography": self.cinematography,
            "rendering_spec": self.rendering_spec,
            "production_context": self.production_context,
            "regions": self.regions,
            "art_ontology_matches": self.art_ontology_matches,
            "possible_tasks": self.possible_tasks,
            "uncertainties": self.uncertainties,
            "confidence": self.confidence,
            "media_type": self.media_type,
            "evidence": self.evidence,
        }


