def _sample_positions(frame_total: int, sample_count: int) -> list[int]:
    if frame_total <= 1:
        return [0]
    if sample_count <= 1:
        return [frame_total // 2]
    return [
        max(0, min(frame_total - 1, int(round(i * (frame_total - 1) / (sample_count - 1)))))
        for i in range(sample_count)
    ]


def _dedupe_palette(colors: Iterable[str], limit: int = 6) -> list[str]:
    unique: list[str] = []
    seen: set[str] = set()
    for color in colors:
        key = str(color).upper()
        if key in seen:
            continue
        seen.add(key)
        unique.append(key)
        if len(unique) >= limit:
            break
    return unique


