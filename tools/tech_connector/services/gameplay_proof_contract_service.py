_KEY_PATTERN = re.compile(r"['\"]([A-Za-z0-9_]+)['\"]|key\s+'([A-Za-z0-9]+)'|InputKey\s+(\w+)", re.IGNORECASE)
_ASSET_PATTERN = re.compile(r"/Game/[A-Za-z0-9_/]+", re.IGNORECASE)
_MOVE_MODE_PATTERN = re.compile(r"MOVE_([A-Za-z]+)", re.IGNORECASE)
_STAMINA_PATTERN = re.compile(r"stamina|energy|mana|resource", re.IGNORECASE)
_ANIM_CLIP_PATTERN = re.compile(r"\b(anim(?:ation)?|montage|clip|sequence|slot)\b", re.IGNORECASE)
_GAS_PATTERN = re.compile(r"\b(gameplay\s*ability|GAS|GA_|GE_|GameplayEffect|AbilitySystemComponent)\b", re.IGNORECASE)
_TRACE_PATTERN = re.compile(r"\b(capsule|sphere|line|box)\s*trace\b", re.IGNORECASE)
_COMPILE_CLAIM_WORDS = re.compile(r"\b(compile|save|save\s+loaded|EditorAssetLibrary\.save)\b", re.IGNORECASE)
_RETARGET_PATTERN = re.compile(r"\b(retarget|retargeting|IK\s*retarget)\b", re.IGNORECASE)
_GRAVITY_PATTERN = re.compile(r"\b(gravity\s*scale|GravityScale)\b", re.IGNORECASE)
_DAMAGE_PATTERN = re.compile(r"\b(damage|health|hp|hit\s*points)\b", re.IGNORECASE)
_UI_PATTERN = re.compile(r"\b(?:UMG|widget|HUD|UI|WBP_[A-Za-z0-9_]*|UserWidget)\b", re.IGNORECASE)
_PCG_PATTERN = re.compile(r"\b(PCG|procedural\s+content|foliage\s+spawner)\b", re.IGNORECASE)
_MAYA_RIG_PATTERN = re.compile(r"\b(HIK|FK|IK|control\s+rig|joint|rig)\b", re.IGNORECASE)
_MM_PATTERN = re.compile(r"\b(motion\s*matching|PoseSearch|PSD_)\b", re.IGNORECASE)
_INVULN_PATTERN = re.compile(r"invulner|invincib|iframe|i-frame", re.IGNORECASE)
_NETWORK_PATTERN = re.compile(r"\b(replicate|server|client|authority|multiplay)\b", re.IGNORECASE)


def _extract_keys(text: str) -> list[str]:
    keys = []
    for m in _KEY_PATTERN.finditer(text):
        k = m.group(1) or m.group(2) or m.group(3)
        if k:
            keys.append(k.upper())
    return list(dict.fromkeys(keys))


def _extract_assets(text: str) -> list[str]:
    return list(dict.fromkeys(_ASSET_PATTERN.findall(text)))


def _extract_move_modes(text: str) -> list[str]:
    return list(dict.fromkeys(f"MOVE_{m.group(1)}" for m in _MOVE_MODE_PATTERN.finditer(text)))


def _slugify(text: str) -> str:
    return re.sub(r"[^a-z0-9]+", "_", text.lower()).strip("_")[:60]


