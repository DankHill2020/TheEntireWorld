def extract_proof_claims_from_prompt(prompt: str) -> list[ProofClaim]:
    """Deterministically extract machine-checkable proof claims from a prompt.

    Does NOT call any LLM.  Uses pattern matching on the prompt text to
    identify which gameplay systems are involved and builds one or more
    ``ProofClaim`` objects for each detected system.
    """
    lower = (prompt or "").lower()
    claims: list[ProofClaim] = []

    # Always add the compilation-is-not-done sentinel
    claims.append(_claim_compile_is_not_done())

    # Key/Input bindings
    for key in _extract_keys(lower):
        claims.append(_claim_key_trigger(key, lower))

    # Movement mode transitions
    for mode in _extract_move_modes(lower):
        claims.append(_claim_movement_mode(mode, lower))

    # Stamina / resource drain
    if _STAMINA_PATTERN.search(lower):
        claims.append(_claim_stamina(lower))

    # Capsule/Line traces
    if _TRACE_PATTERN.search(lower):
        claims.append(_claim_trace(lower))

    # AnimGraph / Output Pose
    if _ANIM_CLIP_PATTERN.search(lower):
        claims.append(_claim_animgraph_output_pose(lower))

    # Skeleton compatibility
    if _RETARGET_PATTERN.search(lower) or "mixamo" in lower or "fbx" in lower:
        assets = _extract_assets(lower)
        claims.append(_claim_skeleton_compatibility(assets, lower))

    # GAS / Gameplay Abilities
    if _GAS_PATTERN.search(prompt):  # use original prompt (preserves case for GA_/GE_)
        claims.append(_claim_gas_ability(lower, original_prompt=prompt))

    # Maya HIK rigging
    if _MAYA_RIG_PATTERN.search(lower) and "maya" in lower:
        claims.append(_claim_hik_rig(lower))

    # Invulnerability / iframes (search original prompt for mixed case)
    if _INVULN_PATTERN.search(prompt):
        claims.append(_claim_invulnerability(lower))

    # UMG / Widget state binding (search original prompt for mixed case)
    if _UI_PATTERN.search(prompt):
        claims.append(_claim_umg_binds_real_state(lower))

    # PCG / Foliage
    if _PCG_PATTERN.search(prompt):
        claims.append(_claim_pcg_affects_level(lower))

    # Network/replication
    if _NETWORK_PATTERN.search(lower):
        claims.append(_claim_network_authority(lower))

    existing_ids = {claim.claim_id for claim in claims}
    for claim in _generic_vertical_slice_claims(prompt):
        if claim.claim_id not in existing_ids:
            claims.append(claim)
            existing_ids.add(claim.claim_id)

    # Deduplicate by claim_id (keep first)
    seen: set[str] = set()
    unique: list[ProofClaim] = []
    for c in claims:
        if c.claim_id not in seen:
            seen.add(c.claim_id)
            unique.append(c)
    return unique


def _build_gameplay_contract_from_prompt(prompt: str) -> GameplayContract:
    from tech_connector.services.unreal.evidence_driven_feature_synthesis_service import (
        derive_prompt_requirement_contract,
    )

    lower = (prompt or "").lower()
    keys = _extract_keys(lower)
    modes = _extract_move_modes(lower)
    assets = _extract_assets(prompt)
    requirement = derive_prompt_requirement_contract(prompt)
    explicit = dict(requirement.get("explicit") or {})
    prompt_inputs = list(explicit.get("inputs") or [])
    timing = list(explicit.get("timing") or [])

    # Feature name
    feature_name = "Unknown Feature"
    if "climbing" in lower or "climb" in lower:
        feature_name = "Wall Climbing"
    elif "grapple" in lower or "grappling" in lower:
        feature_name = "Grappling Hook"
    elif "dodge" in lower or "roll" in lower:
        feature_name = "Combat Dodge Roll"
    elif "rig" in lower and "maya" in lower:
        feature_name = "Maya Character Rig"
    elif "foliage" in lower or "pcg" in lower:
        feature_name = "Procedural Foliage PCG"
    elif "motion matching" in lower:
        feature_name = "Motion Matching Combat"
    elif "stamina" in lower:
        feature_name = "Stamina System"

    trigger_key = keys[0] if keys else None
    trigger = str(explicit.get("activation") or "") or (
        f"Player presses key '{trigger_key}' through the active input mapping"
        if trigger_key else
        "The intended public gameplay event resolved during architecture planning"
    )

    preconditions = ["Character is possessed and alive"]
    if _STAMINA_PATTERN.search(lower):
        preconditions.append("StaminaAttribute > 0")
    if _TRACE_PATTERN.search(lower):
        preconditions.append("A compatible surface is within trace range")
    if _GAS_PATTERN.search(prompt):
        preconditions.append("Gameplay Ability is granted to AbilitySystemComponent")
    if any(value in lower for value in ("wall", "surface", "target", "obstacle")):
        preconditions.append("A compatible world target is detected and remains valid")

    runtime_behavior = []
    if _TRACE_PATTERN.search(lower):
        runtime_behavior.append("Capsule/Line trace runs from actor location along forward vector")
    if modes:
        runtime_behavior.append(f"CharacterMovementComponent.MovementMode is set to {modes[0]}")
    if _GRAVITY_PATTERN.search(lower):
        runtime_behavior.append("GravityScale is set to 0.0")
    if _STAMINA_PATTERN.search(lower):
        runtime_behavior.append("Stamina drains at declared rate per second via Gameplay Effect")
    if _ANIM_CLIP_PATTERN.search(lower):
        runtime_behavior.append("Animation state machine transitions to the appropriate state")
    if prompt_inputs:
        runtime_behavior.append("Input state is measured from " + " or ".join(prompt_inputs))
    if timing:
        runtime_behavior.append("Activation guard enforces " + str(timing[0].get("source_text") or "the declared threshold"))
    runtime_behavior.append("Authoritative feature state has explicit enter, update, exit, cancel, and recovery paths")

    state_changes = []
    if modes:
        state_changes.append(f"MovementMode = {modes[0]}")
    if _GRAVITY_PATTERN.search(lower):
        state_changes.append("GravityScale = 0.0")
    if _GAS_PATTERN.search(prompt):
        state_changes.append("Gameplay ability tag applied to character")
    if _STAMINA_PATTERN.search(lower):
        state_changes.append("StaminaAttribute decremented by GameplayEffect")
    if _INVULN_PATTERN.search(prompt):
        state_changes.append("Invulnerability Gameplay Tag added for duration")
    if _RETARGET_PATTERN.search(lower) or "mixamo" in lower or "fbx" in lower:
        state_changes.append("AnimSequence skeleton reference updated to target skeleton")
    if _PCG_PATTERN.search(prompt):
        state_changes.append("PCG Component spawned instances placed in level")
    if _UI_PATTERN.search(prompt):
        state_changes.append("UMG widget binding updated to reflect live attribute value")
    if not state_changes:
        state_changes.append("Resolved authoritative feature state changes from inactive to active and back to baseline")

    player_visible = "Character responds to input with the expected movement/animation transition"
    if "climbing" in lower:
        player_visible = "Character physically moves along wall surface in the climbing animation"
    elif "dodge" in lower:
        player_visible = "Character rolls in the input direction; invulnerable during roll"

    cancellation_terms = ["a required target becomes invalid", "a blocking state is entered"]
    if prompt_inputs:
        cancellation_terms.insert(0, "the player releases the required input")
    if _STAMINA_PATTERN.search(lower):
        cancellation_terms.append("the requested resource is depleted")
    cancellation = "Feature exits when " + ", ".join(cancellation_terms) + "; all modified state is restored"
    if modes:
        cancellation += f"; MovementMode returns to MOVE_Walking; GravityScale restored"

    invalid_conditions = [
        "No surface within trace range → ability activation rejected, no state change",
        "Insufficient stamina → activation blocked",
        "AbilitySystemComponent not initialized → null-safe failure, log error",
        "Animation clip missing → ability still functions, log warning",
        "Input pressed during blocking ability state → ignored",
    ]

    invalid_conditions = [
        "Required target or world condition unavailable -> activation rejected with no persistent state change",
        "Input attempted during a blocking state -> ignored or queued according to the resolved ownership policy",
        "Required runtime reference unavailable -> null-safe failure with a structured diagnostic",
    ]
    if timing:
        invalid_conditions.append("Input released before the declared threshold -> timer cancelled and activation rejected")
    if _STAMINA_PATTERN.search(lower):
        invalid_conditions.append("Insufficient requested resource -> activation blocked")
    if _ANIM_CLIP_PATTERN.search(lower) or "abp" in lower:
        invalid_conditions.append("Required animation role missing or contextually invalid -> feature cannot be reported complete")

    integration = []
    if assets:
        integration.append(f"Assets modified: {', '.join(assets[:4])}")
    if _GAS_PATTERN.search(prompt):
        integration.append("AbilitySystemComponent receives and tracks ability state")
    if _UI_PATTERN.search(lower):
        integration.append("UMG widget updates from live gameplay state")
    if _NETWORK_PATTERN.search(lower):
        integration.append("Server holds authoritative state; clients receive replicated values")

    return GameplayContract(
        feature_name=feature_name,
        trigger=trigger,
        preconditions=preconditions,
        runtime_behavior=runtime_behavior,
        state_changes=state_changes,
        player_visible_result=player_visible,
        completion_or_cancellation=cancellation,
        invalid_conditions=invalid_conditions,
        integration_criteria=integration,
    )


def _build_validation_ladder(claims: list[ProofClaim]) -> list[dict[str, Any]]:
    """Produce the 6-milestone ladder with counts of claims per level."""
    ladder = []
    for level, label in EVIDENCE_LEVEL_LABELS.items():
        level_claims = [c for c in claims if c.evidence_level == level]
        passed = [c for c in level_claims if c.status == "passed"]
        ladder.append({
            "milestone": level,
            "label": label,
            "claim_count": len(level_claims),
            "passed_count": len(passed),
            "complete": len(level_claims) > 0 and len(passed) == len(level_claims),
            "claim_ids": [c.claim_id for c in level_claims],
        })
    return ladder


def build_gameplay_proof_contract(
    prompt: str,
    *,
    feature_name: str = "",
) -> GameplayProofContract:
    """Build a fully structured, machine-checkable :class:`GameplayProofContract`.

    Parameters
    ----------
    prompt:
        The raw user prompt text.
    feature_name:
        Optional override for the feature name label.

    Returns
    -------
    GameplayProofContract
        Ready to be consumed by the planner, progress service, and
        evidence gatherers. ``is_done`` will be ``False`` until all
        ``ProofClaim`` objects are marked ``"passed"`` by the
        validation pipeline.
    """
    gameplay_contract = _build_gameplay_contract_from_prompt(prompt)
    if feature_name:
        gameplay_contract.feature_name = feature_name
    claims = extract_proof_claims_from_prompt(prompt)
    ladder = _build_validation_ladder(claims)

    return GameplayProofContract(
        feature_name=feature_name or gameplay_contract.feature_name,
        gameplay_contract=gameplay_contract,
        proof_claims=claims,
        validation_ladder=ladder,
        compilation_is_not_done=True,
        self_repair_notes=[],
    )


def record_claim_evidence(
    contract: GameplayProofContract,
    claim_id: str,
    observed: str,
    passed: bool,
    origin: str = "model_inference",
) -> None:
    """Record runtime evidence against a specific proof claim in-place.

    Parameters
    ----------
    contract:
        The :class:`GameplayProofContract` to update.
    claim_id:
        The ``claim_id`` of the :class:`ProofClaim` to update.
    observed:
        Human-readable description of what was observed.
    passed:
        Whether the observation satisfies the claim's ``then_assertion``.
    origin:
        The source of the evidence. Must be a trusted origin to satisfy runtime claims.
    """
    for claim in contract.proof_claims:
        if claim.claim_id == claim_id:
            claim.evidence_observed = observed
            claim.evidence_origin = origin
            
            # Trust rules:
            is_valid_pass = False
            if passed:
                if origin in ("unreal_runtime", "unreal_automation", "unreal_functional_test"):
                    is_valid_pass = True
                elif origin == "static_analysis" and claim.evidence_level == 1:
                    is_valid_pass = True
                elif origin == "human_observation":
                    is_valid_pass = True
                    
            claim.status = "passed" if is_valid_pass else "failed"
            return
    # Not found – append a new claim
    contract.proof_claims.append(
        ProofClaim(
            claim_id=claim_id,
            when_trigger="(from runtime evidence recording)",
            then_assertion="(not pre-declared)",
            evidence_observed=observed,
            evidence_origin=origin,
            status="passed" if (passed and origin in ("unreal_runtime", "unreal_automation", "unreal_functional_test")) else "failed",
        )
    )


