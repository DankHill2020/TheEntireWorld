# coding=utf-8
"""Gameplay Proof Contract Service for Tech Connector.

Redefines "done" for gameplay feature requests.

A feature is only complete when:
  1. Structural correctness  – compilation, reference resolution, no dead code.
  2. Runtime execution       – trigger fires, execution path is reached.
  3. Gameplay behavior       – state changes match the declared THEN-claims.
  4. Integration correctness – connected systems receive/respond correctly.
  5. Failure/edge handling   – invalid conditions fail safely.
  6. Evidence-backed proof   – every THEN-claim has an observable assertion.

Compilation alone satisfies milestone 1 only.

The central output of this service is a :class:`GameplayProofContract`
containing machine-checkable ``ProofClaim`` objects expressed as::

    WHEN  <trigger>
    AND   <precondition> (zero or more)
    THEN  <observable assertion>   → pass/fail/pending

Downstream services (planner, goal_gap_planning_service, progress service)
should consume the proof contract so that partial or unverified claims block
marking a task "done".
"""

from __future__ import annotations

import re
from dataclasses import asdict, dataclass, field
from typing import Any


# ---------------------------------------------------------------------------
# Evidence levels - mirrors the 6-milestone ladder in the design doc.
# ---------------------------------------------------------------------------

EVIDENCE_LEVEL_LABELS = {
    1: "static_validation",          # Compiles, references resolve, no dead code
    2: "construction_validation",    # Instantiation, initialization, delegates bound
    3: "runtime_path_validation",    # Trigger fires, execution path reached, cleanup runs
    4: "gameplay_outcome_validation",# Observable state: HP changed, actor moved, UI updated
    5: "negative_edge_validation",   # Null ref, repeat activation, insufficient resource
    6: "regression_validation",      # Adjacent systems unbroken, no input/anim conflicts
}


# ---------------------------------------------------------------------------
# Dataclasses
# ---------------------------------------------------------------------------

@dataclass
class ProofClaim:
    """One machine-checkable assertion.

    Instances are generated by :func:`extract_proof_claims_from_prompt`.

    Attributes
    ----------
    claim_id:
        Stable short identifier, e.g. ``"movement_mode_flying"``.
    when_trigger:
        The activating event or player input (e.g. ``"IA_Climb is pressed"``).
    preconditions:
        Zero or more AND-conditions that must be true before activation.
    then_assertion:
        The observable outcome that must be verified (e.g.
        ``"CharacterMovementComponent.MovementMode == MOVE_Flying"``).
    evidence_level:
        Minimum milestone (1–6) required to satisfy this claim.
    validation_method:
        How to gather evidence: ``"pil_log"``, ``"state_query"``,
        ``"automation_test"``, ``"screenshot"``, ``"runtime_assertion"``, etc.
    failure_modes:
        Known false-positive conditions that would make the feature *appear*
        to work while actually being disconnected or incomplete.
    status:
        ``"pending"`` / ``"passed"`` / ``"failed"`` / ``"untestable"``.
    evidence_observed:
        Human-readable log of what was actually observed during validation.
    """

    claim_id: str
    when_trigger: str
    preconditions: list[str] = field(default_factory=list)
    then_assertion: str = ""
    evidence_level: int = 3
    validation_method: str = "runtime_assertion"
    failure_modes: list[str] = field(default_factory=list)
    status: str = "pending"
    evidence_observed: str = ""
    evidence_origin: str = "model_inference"
    observation_spec: dict[str, Any] = field(default_factory=dict)

    def to_dict(self) -> dict[str, Any]:
        return asdict(self)

    def render_claim(self) -> str:
        """Render as a human-readable WHEN/AND/THEN block."""
        lines = [f"WHEN  {self.when_trigger}"]
        for cond in self.preconditions:
            lines.append(f"AND   {cond}")
        lines.append(f"THEN  {self.then_assertion}")
        lines.append(f"  evidence_level : {self.evidence_level} ({EVIDENCE_LEVEL_LABELS.get(self.evidence_level, '?')})")
        lines.append(f"  validate_via   : {self.validation_method}")
        lines.append(f"  status         : {self.status}")
        if self.evidence_observed:
            lines.append(f"  observed       : {self.evidence_observed}")
        if self.failure_modes:
            lines.append(f"  false-positives: {'; '.join(self.failure_modes)}")
        return "\n".join(lines)


@dataclass
class GameplayContract:
    """Behavioral contract derived deterministically from the prompt.

    This is the definition of done for the feature.

    Attributes
    ----------
    feature_name:
        Short label for the feature.
    trigger:
        What activates the feature (input, event, notify, state transition).
    preconditions:
        State that must be true before activation is accepted.
    runtime_behavior:
        What must happen while the feature is active.
    state_changes:
        Variables, components, tags, attributes, transforms that must change.
    player_visible_result:
        What the player sees, hears, or controls.
    completion_or_cancellation:
        What ends the feature and what state is restored.
    invalid_conditions:
        Inputs that should be rejected, and expected fail-safe behavior.
    integration_criteria:
        Which existing systems must receive or respond to the result.
    """

    feature_name: str
    trigger: str = ""
    preconditions: list[str] = field(default_factory=list)
    runtime_behavior: list[str] = field(default_factory=list)
    state_changes: list[str] = field(default_factory=list)
    player_visible_result: str = ""
    completion_or_cancellation: str = ""
    invalid_conditions: list[str] = field(default_factory=list)
    integration_criteria: list[str] = field(default_factory=list)

    def to_dict(self) -> dict[str, Any]:
        return asdict(self)

    def render_contract(self) -> str:
        lines = [f"## Gameplay Contract: {self.feature_name}"]
        lines.append(f"**Trigger**: {self.trigger or '(not yet resolved)'}")
        if self.preconditions:
            lines.append("**Preconditions**:")
            for p in self.preconditions:
                lines.append(f"  - {p}")
        if self.runtime_behavior:
            lines.append("**Runtime Behavior**:")
            for b in self.runtime_behavior:
                lines.append(f"  - {b}")
        if self.state_changes:
            lines.append("**State Changes**:")
            for s in self.state_changes:
                lines.append(f"  - {s}")
        if self.player_visible_result:
            lines.append(f"**Player-Visible Result**: {self.player_visible_result}")
        if self.completion_or_cancellation:
            lines.append(f"**Completion/Cancellation**: {self.completion_or_cancellation}")
        if self.invalid_conditions:
            lines.append("**Invalid Conditions (must fail-safe)**:")
            for c in self.invalid_conditions:
                lines.append(f"  - {c}")
        if self.integration_criteria:
            lines.append("**Integration Criteria**:")
            for i in self.integration_criteria:
                lines.append(f"  - {i}")
        return "\n".join(lines)


@dataclass
class GameplayProofContract:
    """Full proof contract for a gameplay feature implementation request.

    Produced by :func:`build_gameplay_proof_contract` and consumed by
    downstream planners and progress services to determine whether the
    feature is truly done.

    Attributes
    ----------
    feature_name:
        Human-readable name of the feature being implemented.
    gameplay_contract:
        Behavioral specification (trigger, preconditions, state changes, …).
    proof_claims:
        Machine-checkable WHEN/AND/THEN assertions.  Every claim must be
        ``"passed"`` for the feature to be marked done.
    validation_ladder:
        Ordered list of the 6 milestone levels with their completion status.
    is_done:
        True only when all proof_claims are ``"passed"`` and all six
        milestone levels have at least one satisfied claim.
    compilation_is_not_done:
        Always True – reminds downstream code that compilation alone does
        not satisfy this contract.
    missing_evidence:
        Claims that remain ``"pending"`` or ``"failed"`` at the time of
        inspection.
    self_repair_notes:
        Accumulated notes from the self-repair loop.
    """

    feature_name: str
    gameplay_contract: GameplayContract = field(default_factory=lambda: GameplayContract(""))
    proof_claims: list[ProofClaim] = field(default_factory=list)
    validation_ladder: list[dict[str, Any]] = field(default_factory=list)
    compilation_is_not_done: bool = True
    self_repair_notes: list[str] = field(default_factory=list)

    @property
    def is_done(self) -> bool:
        """True only when every proof claim has been passed."""
        return bool(self.proof_claims) and all(
            c.status == "passed" for c in self.proof_claims
        )

    @property
    def missing_evidence(self) -> list[ProofClaim]:
        return [c for c in self.proof_claims if c.status != "passed"]

    def to_dict(self) -> dict[str, Any]:
        d = asdict(self)
        d["is_done"] = self.is_done
        d["missing_evidence_ids"] = [c.claim_id for c in self.missing_evidence]
        d["framework"] = "gameplay_proof_contract_v1"
        return d

    def render_proof_block(self) -> str:
        """Render the complete proof contract as human-readable text."""
        lines = [
            "=" * 72,
            f"GAMEPLAY PROOF CONTRACT: {self.feature_name}",
            f"Done: {self.is_done}  |  "
            f"Compilation = milestone 1 only, NOT done",
            "=" * 72,
        ]
        lines.append(self.gameplay_contract.render_contract())
        lines.append("")
        lines.append("## Proof Claims")
        for claim in self.proof_claims:
            lines.append("")
            lines.append(claim.render_claim())
        if self.missing_evidence:
            lines.append("")
            lines.append(
                f"## ⚠  OUTSTANDING ({len(self.missing_evidence)} claims not yet passed)"
            )
            for c in self.missing_evidence:
                lines.append(f"  [{c.status.upper()}] {c.claim_id}: {c.then_assertion}")
        lines.append("=" * 72)
        return "\n".join(lines)


